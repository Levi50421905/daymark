function timestamp(dateISO: string, hour = 10, minute = 0): string {
  return new Date(`${dateISO}T${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}:00`).toISOString()
}

function makeTransaction(
  type: Transaction['type'],
  categoryId: string,
  amount: number,
  date: string,
  note: string,
  hour = 10,
): Transaction {
  return {
    id: uid('tx'),
    type,
    categoryId,
    amount,
    date,
    note,
    createdAt: timestamp(date, hour),
  }
}

/** Build a transaction for a shopping list without duplicating it. */
export function applyShoppingListToFinance(
  list: ShoppingList,
  categoryId: string,
  date: string,
): Transaction {
  const totals = getShoppingTotals(list)
  const amount = totals.purchasedCount > 0 ? totals.actualTotal : totals.estimatedTotal
  if (amount <= 0) {
    throw new Error('Daftar belanja ini belum punya nominal untuk dicatat.')
  }
  return {
    id: uid('tx'),
    type: 'expense',
    categoryId,
    amount,
    date,
    note: `Belanja: ${list.name}`,
    createdAt: new Date().toISOString(),
    source: { kind: 'shopping', id: list.id },
  }
}

